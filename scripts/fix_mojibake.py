def fix_mojibake(input_path: str, output_path: str | None = None) -> tuple[int, int]:
    """
    Fix mojibake in a file.
    
    Args:
        input_path: Path to file with mojibake
        output_path: Path for fixed file (default: overwrite input)
        
    Returns:
        Tuple of (lines_fixed, replacements_made)
    """
    if output_path is None:
        output_path = input_path
        
    with open(input_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    original = content
    replacements_made = 0
    
    # Sort by length (longest first) to avoid partial replacements
    sorted_replacements = sorted(REPLACEMENTS.items(), key=lambda x: len(x[0]), reverse=True)
    
    for mojibake, chinese in sorted_replacements:
        if mojibake in content:
            count = content.count(mojibake)
            content = content.replace(mojibake, chinese)
            replacements_made += count
            print(f"  Replaced {count}x: {mojibake[:30]}... → {chinese}")
    
    # Count lines changed
    original_lines = set(original.split('\n'))
    new_lines = set(content.split('\n'))
    lines_fixed = len(original_lines - new_lines)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return lines_fixed, replacements_made


